"""Explicit evidence for the contract's time-determinism claim.

The contract uses ``datetime.datetime.now(datetime.timezone.utc)``
(``AgentVerdictOS._now_dt()``) for every deadline/challenge-window
comparison, because this pinned (v0.2.x-era) runner's SDK has no
dedicated clock function (confirmed: the pinned SDK at
``genlayer/gl/__init__.py`` only exposes ``trace_time_micro()`` for
profiling; `gl.vm.get_timestamp()` was added in a later SDK generation
and does not exist in this pin -- see docs/GENLAYER_CAPABILITY_MATRIX.md
section 3).

What this test file actually proves, and what it does NOT prove:

- It proves that ``gltest``'s direct-mode ``VMContext.warp()`` cheatcode
  controls exactly what ``datetime.datetime.now(UTC)`` returns inside a
  contract method call, with microsecond-exact identity, and that the
  effect is live/dynamic (a second warp() changes the observed value
  again within the same deployed contract instance). This is real,
  executed evidence from this session, not an assumption.
- It does NOT prove that the real GenVM WASM runtime (Wasmtime-sandboxed,
  used by StudioNet / a real ``genlayer up`` deployment) virtualizes the
  WASI clock for plain ``datetime.datetime.now()`` calls in the exact
  same way. ``gltest``'s direct mode runs contract code natively in
  CPython on the host, patching ``datetime.datetime`` at the Python
  level (see ``gltest/direct/vm.py::VMContext.activate()``) -- it is a
  test-harness simulation, not the production WASM sandbox. The
  corroborating evidence for the production runtime (not generated by
  this test) is documentary: the current GenVM spec
  (sdk.genlayer.com/main, fetched live this session) states WASI's time
  functions are "Modified to ensure reproducible behavior across
  validators" as part of the "Modified Wasmtime Runtime", and that real
  wall-clock time is exposed to a contract only under the
  ``unsafe-tracing`` debug level, which a consensus-network host "must
  not" accept from untrusted callers. No live WASM-level execution of
  this exact contract against a real GenVM binary was performed this
  session (no Docker-backed ``genlayer up`` network was available/used
  for this specific check) -- see docs/SECURITY_THREAT_MODEL.md and the
  audit report delivered this session for the full citation chain.
"""

import datetime

from conftest import API_MODULE, POLICY_ID, make_rubric


def test_warp_controls_datetime_now_with_exact_identity(deployed, direct_vm, direct_alice, direct_bob):
    """warp() to a specific instant; the contract's own _now_dt()-derived
    created_at field must equal that exact instant, not merely be
    "later than before". This is a stronger assertion than the existing
    deadline-comparison tests (which only check before/after a deadline).
    """
    warped_1 = "2500-03-14T15:09:26Z"
    direct_vm.warp(warped_1)

    direct_vm.sender = direct_alice
    agreement_id = deployed.create_agreement(
        direct_bob, POLICY_ID, API_MODULE, 1000, "2999-01-01T00:00:00Z", make_rubric(),
    )
    ag = deployed.get_agreement(agreement_id)
    assert ag["created_at"] == warped_1, (
        f"expected created_at to exactly equal the warped instant {warped_1!r}, "
        f"got {ag['created_at']!r} -- datetime.datetime.now(UTC) is not reading "
        f"the warped clock"
    )

    # A second, different warp() must change the observed value again --
    # proving this is live interception (re-read on every call), not a
    # one-time snapshot cached at deploy time. A second independent
    # agreement created after the re-warp must carry the NEW timestamp,
    # while the first agreement's already-recorded created_at must stay
    # exactly as it was (no retroactive mutation of past state).
    warped_2 = "2500-03-14T16:00:00Z"
    direct_vm.warp(warped_2)
    direct_vm.sender = direct_alice
    agreement_id_2 = deployed.create_agreement(
        direct_bob, POLICY_ID, API_MODULE, 2000, "2999-01-01T00:00:00Z", make_rubric(),
    )
    ag_2 = deployed.get_agreement(agreement_id_2)
    assert ag_2["created_at"] == warped_2
    ag_1_again = deployed.get_agreement(agreement_id)
    assert ag_1_again["created_at"] == warped_1


def test_default_unwarped_clock_is_a_real_parseable_utc_instant(deployed, direct_vm, direct_alice, direct_bob):
    """Without any warp() call, _now_dt() must still return a real,
    parseable UTC-ish instant (gltest's VMContext defaults ``_datetime``
    to a fixed epoch, not an exception) -- i.e. the contract never
    crashes or silently defaults to an empty/sentinel value when no test
    explicitly warps time. This guards against a regression where
    ``_now_dt()`` starts raising or returning a non-ISO string.
    """
    direct_vm.sender = direct_alice
    agreement_id = deployed.create_agreement(
        direct_bob, POLICY_ID, API_MODULE, 1000, "2999-01-01T00:00:00Z", make_rubric(),
    )
    ag = deployed.get_agreement(agreement_id)
    # Must be ISO-8601 parseable with a timezone, and not the Unix epoch
    # sentinel a broken clock mock might fall back to.
    parsed = datetime.datetime.fromisoformat(ag["created_at"].replace("Z", "+00:00"))
    assert parsed.tzinfo is not None
    assert parsed.year > 1970
